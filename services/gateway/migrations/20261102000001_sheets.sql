-- Phase 2: sheets, their visuals, and sheet sharing (docs/adr/0005).

CREATE TABLE sheets (
    id               uuid PRIMARY KEY DEFAULT uuidv7(),
    project_id       uuid NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    name             text NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
    position         int NOT NULL,
    -- Sheet filter definitions with their default values: [{id, column, label, kind, value}].
    filters          jsonb NOT NULL DEFAULT '[]'::jsonb,
    -- Bumped on every save; a save names the version it edited (optimistic concurrency).
    version          bigint NOT NULL DEFAULT 1,
    -- Link sharing (design screen 07). Links always grant view access to this sheet only.
    link_audience    text NOT NULL DEFAULT 'off'
                     CHECK (link_audience IN ('off', 'invited', 'workspace', 'public')),
    link_token       text UNIQUE,
    link_expires_at  timestamptz,
    allow_export     boolean NOT NULL DEFAULT false,
    track_views      boolean NOT NULL DEFAULT true,
    -- Phase 4: whether link viewers may ask the copilot about this sheet.
    allow_copilot    boolean NOT NULL DEFAULT false,
    created_by       uuid REFERENCES users (id) ON DELETE SET NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_by       uuid REFERENCES users (id) ON DELETE SET NULL,
    updated_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sheets_project_id_idx ON sheets (project_id, position);

CREATE TABLE visuals (
    -- Generated by the client, so an unsaved visual already has its final id (undo/redo,
    -- cross-filter selections).
    id        uuid PRIMARY KEY,
    sheet_id  uuid NOT NULL REFERENCES sheets (id) ON DELETE CASCADE,
    position  int NOT NULL,
    spec      jsonb NOT NULL,
    -- Grid placement in grid units: {x, y, w, h}.
    layout    jsonb NOT NULL
);
CREATE INDEX visuals_sheet_id_idx ON visuals (sheet_id, position);

-- People invited to one sheet only: they can open its link but nothing else in the project.
CREATE TABLE sheet_members (
    sheet_id  uuid NOT NULL REFERENCES sheets (id) ON DELETE CASCADE,
    user_id   uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    added_by  uuid REFERENCES users (id) ON DELETE SET NULL,
    added_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (sheet_id, user_id)
);
CREATE INDEX sheet_members_user_id_idx ON sheet_members (user_id);

-- Opens of a shared link, when the sheet tracks views (user_id is null for anonymous viewers).
CREATE TABLE sheet_views (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    sheet_id   uuid NOT NULL REFERENCES sheets (id) ON DELETE CASCADE,
    user_id    uuid REFERENCES users (id) ON DELETE SET NULL,
    viewed_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sheet_views_sheet_id_idx ON sheet_views (sheet_id, viewed_at DESC);
